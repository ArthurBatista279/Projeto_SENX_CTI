CREATE DATABASE CTI_Chamadas;

GO

USE CTI_Chamadas;

GO

CREATE TABLE Equipe(
    IdEquipe UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,

    Nome NVARCHAR(255) NOT NULL,
    Departameo NVARCHAR(255) NOT NULL,

);

CREATE TABLE Usuario(
    IdUsuario UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,
    IdEquipe UNIQUEIDENTIFIER NOT NULL,

    Nome NVARCHAR(200) NOT NULL,
    Email NVARCHAR(255) NOT NULL UNIQUE,
    Imagem NVARCHAR(255) NOT NULL,
    Cargo NVARCHAR(255) NOT NULL,
    Senha NVARCHAR(40) NOT NULL,

    FOREIGN KEY (IdEquipe) REFERENCES Equipe(IdEquipe)
);

CREATE TABLE DadosCliente(
    IdDadosCliente UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,
    IdUsuario UNIQUEIDENTIFIER NOT NULL,

    Nome NVARCHAR(255) NOT NULL,
    Email NVARCHAR(255) NOT NULL UNIQUE,
    Telefone NVARCHAR(11) NOT NULL UNIQUE,
    Situacao NVARCHAR(255) NOT NULL,
    Consentimento BIT NOT NULL,

    FOREIGN KEY (IdUsuario) REFERENCES Usuario(IdUsuario)
);

CREATE TABLE Ligacao(
    IdLigacao UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,
    IdFuncionario UNIQUEIDENTIFIER NOT NULL,
    IdCliente UNIQUEIDENTIFIER NOT NULL,

    Data_Inicio DATETIME NOT NULL DEFAULT GETUTCDATE(),
    Duracao TIME NOT NULL,
    Numero_Origem NVARCHAR(11) NOT NULL,
    Numero_Destino NVARCHAR(11) NOT NULL,
    Stats NVARCHAR(255) NOT NULL,
    Hash_Audio NVARCHAR(255) NOT NULL,
    Caminho_Arquivo NVARCHAR(255) NOT NULL,
    IdentificadorPABX NVARCHAR(255) NOT NULL,
    Direcao NVARCHAR(255) NOT NULL,

    FOREIGN KEY (IdFuncionario) REFERENCES Usuario(IdUsuario),
    FOREIGN KEY (IdCliente) REFERENCES DadosCliente(IdDadosCliente)
);

CREATE TABLE Assunto(
    IdAssunto UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,

    Nome NVARCHAR(255) NOT NULL,
    Descricao NVARCHAR(255) NOT NULL,
    Categoria NVARCHAR(255) NOT NULL
);

CREATE TABLE LigacaoAssunto(
    IdLigacao UNIQUEIDENTIFIER NOT NULL,
    IdAssunto UNIQUEIDENTIFIER NOT NULL,

    PRIMARY KEY (IdLigacao, IdAssunto),

    FOREIGN KEY (IdLigacao) REFERENCES Ligacao(IdLigacao),
    FOREIGN KEY (IdAssunto) REFERENCES Assunto(IdAssunto)
);

CREATE TABLE Analise(
    IdAnalise UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,
    IdLigacao UNIQUEIDENTIFIER NOT NULL,

    Data_Analise DATETIME NOT NULL DEFAULT GETUTCDATE(),
    ResolucaoEncaminhamento NVARCHAR(255) NOT NULL,
    StatusProcessamento BIT,
    Modelo_Versao NVARCHAR(200) NOT NULL,
    Transcricao_Texto NVARCHAR(MAX) NOT NULL,
    Resumo_Texto NVARCHAR(MAX) NOT NULL,
    Cancelamento BIT NOT NULL,
    Oportunidade BIT NOT NULL,
    ScoreGeral INT NOT NULL,
    ProblemaNecessidade NVARCHAR(255) NOT NULL,
    Compromissos NVARCHAR(255) NOT NULL,

    FOREIGN KEY (IdLigacao) REFERENCES Ligacao(IdLigacao)
);

CREATE TABLE Alerta(
    IdAlerta UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,
    IdAnalise UNIQUEIDENTIFIER NOT NULL,
    IdEquipe UNIQUEIDENTIFIER NOT NULL,
    IdFuncionario UNIQUEIDENTIFIER NOT NULL,

    Tipo NVARCHAR(255) NOT NULL,
    Severidade NVARCHAR(255) NOT NULL,
    Mensagem NVARCHAR(255) NOT NULL,
    StatusTratamento BIT NOT NULL,
    Status_Validacao BIT NOT NULL,
    Validado_em DATETIME NOT NULL DEFAULT GETUTCDATE(),
    Observacao NVARCHAR(255) NOT NULL,
    Criado_em DATETIME NOT NULL DEFAULT GETUTCDATE(),
    Resolvido_em DATETIME NOT NULL DEFAULT GETUTCDATE(),
    Justificativa NVARCHAR(MAX) NOT NULL,
    TrechoEvidencia NVARCHAR(255) NOT NULL,

    FOREIGN KEY (IdAnalise) REFERENCES Analise(IdAnalise),
    FOREIGN KEY (IdEquipe) REFERENCES Equipe(IdEquipe),
    FOREIGN KEY (IdFuncionario) REFERENCES Usuario(IdUsuario)
);

CREATE TABLE Registro(
    IdRegistro UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,
    IdAnalise UNIQUEIDENTIFIER NOT NULL,
    IdFuncionario UNIQUEIDENTIFIER NOT NULL,

    Descricao NVARCHAR(255) NOT NULL,
    Prazo DATETIME NOT NULL DEFAULT GETUTCDATE(),
    Status NVARCHAR(255) NOT NULL,

    FOREIGN KEY (IdAnalise) REFERENCES Analise(IdAnalise),
    FOREIGN KEY (IdFuncionario) REFERENCES Usuario(IdUsuario)
);

CREATE TABLE Criterio(
    IdCriterio UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,

    Nome NVARCHAR(255) NOT NULL,
    Descricao NVARCHAR(255) NOT NULL,
    RegraAvaliacao NVARCHAR(255) NOT NULL,
    Versao NVARCHAR(255) NOT NULL,
    Ativo BIT NOT NULL,

);

CREATE TABLE Resultado(
    IdResultado UNIQUEIDENTIFIER DEFAULT NEWID() PRIMARY KEY NOT NULL,
    IdCriterio UNIQUEIDENTIFIER NOT NULL,
    IdAnalise UNIQUEIDENTIFIER NOT NULL,
    IdFuncionario UNIQUEIDENTIFIER NOT NULL,

    Classificacao NVARCHAR(255) NOT NULL,
    Score INT NOT NULL,
    Justificativa NVARCHAR(255) NOT NULL,
    TrechoEvidencia NVARCHAR(255) NOT NULL,
    ResultadoValidado NVARCHAR(255) NOT NULL,
    StatusValidacao NVARCHAR(255) NOT NULL,
    Validado_em DATETIME NOT NULL DEFAULT GETUTCDATE(),
    ObservacaoValidacao NVARCHAR(255) NOT NULL,

    FOREIGN KEY (IdCriterio) REFERENCES Criterio(IdCriterio),
    FOREIGN KEY (IdAnalise) REFERENCES Analise(IdAnalise),
    FOREIGN KEY (IdFuncionario) REFERENCES Usuario(IdUsuario)
);

